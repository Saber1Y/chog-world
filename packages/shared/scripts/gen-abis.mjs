// Generates typed `as const` ABI modules from Foundry artifacts in contracts/out.
// Run after `forge build`: pnpm --filter @chog-world/shared gen:abis
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const outDir = join(here, "../../../contracts/out");
const target = join(here, "../src/abis");

const CONTRACTS = [
  ["ChogState", "chogStateAbi"],
  ["Treasury", "treasuryAbi"],
  ["ChogItems", "chogItemsAbi"],
  ["QuestBoard", "questBoardAbi"],
  ["Arena", "arenaAbi"],
  ["ChogOperator", "chogOperatorAbi"],
  ["IAccountV3", "accountV3Abi", "IERC6551.sol"],
  ["IERC6551Registry", "erc6551RegistryAbi", "IERC6551.sol"],
  ["EngineHarness", "engineHarnessAbi"],
];

mkdirSync(target, { recursive: true });
const exports = [];
for (const [name, exportName, file] of CONTRACTS) {
  const artifact = JSON.parse(readFileSync(join(outDir, file ?? `${name}.sol`, `${name}.json`), "utf8"));
  const body = `// Generated by scripts/gen-abis.mjs from contracts/out. Do not edit.\nexport const ${exportName} = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`;
  writeFileSync(join(target, `${name}.ts`), body);
  exports.push(`export { ${exportName} } from "./${name}.js";`);
  if (name === "EngineHarness") {
    writeFileSync(
      join(here, "../test/engineHarnessBytecode.ts"),
      `// Generated by scripts/gen-abis.mjs. Do not edit.\nexport const engineHarnessBytecode = "${artifact.bytecode.object}" as const;\n`,
    );
  }
}
writeFileSync(join(target, "index.ts"), `// Generated by scripts/gen-abis.mjs. Do not edit.\n${exports.join("\n")}\n`);
console.log(`wrote ${CONTRACTS.length} ABIs to ${target}`);
